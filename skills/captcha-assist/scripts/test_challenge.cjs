const assert = require('node:assert/strict');
const c = require('./challenge.js');
const target = 'https://aliexpress.ru/item/123.html?sku_id=456&tracking=SECRET';
const gate = 'https://aliexpress.ru/item/123.html/_____tmd_____/punish?x5secdata=SECRET';
(async () => {
  let state = c.begin({target_url:target,browser_id:'1',tab_id:'3',operation_id:'fixture'});
  assert.equal(state.target_url,'https://aliexpress.ru/item/123.html?sku_id=456');
  assert.equal(c.classify(gate,{text:''}).status,'challenge_not_loaded');
  assert.equal(c.classify(gate,{text:'ERR_CONNECTION_CLOSED'}).status,'network_error');
  let view = c.classify(gate,{text:'Verify you are human. '+gate});
  assert.equal(view.status,'challenge_visible');
  assert.ok(!JSON.stringify(view).includes('SECRET'));
  assert.throws(() => c.reserveAttempt(state,c.classify(gate,{text:''})));
  state = c.reserveAttempt(state,view); state = c.reserveAttempt(state,view);
  assert.throws(() => c.reserveAttempt(state,view));
  assert.throws(() => c.reserveAttempt({...state,attempts:0},{...view,url:'https://other.test/captcha'}));
  let current = gate, body = 'Verify you are human';
  const tab = {id:'3',url:async()=>current,playwright:{evaluate:async()=>({text:body})}};
  const ready = {count:async()=>1,isVisible:async()=>true};
  assert.equal((await c.verify(tab,state,ready)).status,'verification_required');
  current = target; body = '';
  assert.equal((await c.verify(tab,state,ready)).status,'verification_required');
  body = 'The expected product and SKU options';
  assert.equal((await c.verify(tab,state,ready)).status,'resumed');
  assert.equal((await c.verify(tab,state,{...ready,isVisible:async()=>false})).status,'verification_required');
  current = 'https://aliexpress.ru/another-page';
  assert.equal((await c.verify(tab,state,ready)).status,'verification_required');
  process.stdout.write('CAPTCHA helper tests passed; no real challenge solved.\n');
})().catch(e=>{console.error(e);process.exitCode=1});
